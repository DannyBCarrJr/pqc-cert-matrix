#!/usr/bin/env python3
"""Phase 1: size table for the chain corpus.

For every cert: total DER bytes, SubjectPublicKeyInfo bytes (extracted via
openssl, which knows the PQ algorithms), signature bytes (minimal DER walk:
Certificate ::= SEQUENCE { tbsCertificate, signatureAlgorithm, signature }),
and the remainder (names, validity, extensions, encoding overhead).

Outputs sizes.json (machine-readable, the source of truth) and ../SIZES.md
(generated table, never hand-edited). Includes the Phase 0 catalyst leaf.
"""
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).parent
CHAINS = HERE / "chains"
CATALYST = HERE.parent / "phase0" / "chains" / "catalyst" / "leaf.crt"


def der_children(buf: bytes):
    """Yield (tag, content) for each TLV inside a DER SEQUENCE body."""
    i = 0
    while i < len(buf):
        tag = buf[i]
        length = buf[i + 1]
        j = i + 2
        if length & 0x80:
            n = length & 0x7F
            length = int.from_bytes(buf[j : j + n], "big")
            j += n
        yield tag, buf[j : j + length]
        i = j + length


def cert_der(path: Path) -> bytes:
    return subprocess.run(
        ["openssl", "x509", "-in", str(path), "-outform", "DER"],
        check=True, capture_output=True,
    ).stdout


def spki_bytes(path: Path) -> int:
    pub = subprocess.run(
        ["openssl", "x509", "-in", str(path), "-pubkey", "-noout"],
        check=True, capture_output=True,
    ).stdout
    der = subprocess.run(
        ["openssl", "pkey", "-pubin", "-outform", "DER"],
        input=pub, check=True, capture_output=True,
    ).stdout
    return len(der)


def measure(path: Path) -> dict:
    der = cert_der(path)
    tag = der[0]
    assert tag == 0x30
    length = der[1]
    j = 2
    if length & 0x80:
        n = length & 0x7F
        j += n
    children = list(der_children(der[j:]))
    assert len(children) == 3, f"{path}: expected 3 top-level elements"
    sig_content = children[2][1]
    sig = len(sig_content) - 1  # first byte = unused-bits count
    spki = spki_bytes(path)
    total = len(der)
    return {
        "file": str(path.relative_to(HERE.parent)),
        "total": total,
        "spki": spki,
        "signature": sig,
        "other": total - spki - sig,
    }


def main() -> None:
    rows = []
    for chain_dir in sorted(CHAINS.iterdir()):
        for crt in sorted(chain_dir.glob("*.crt")):
            rows.append({"chain": chain_dir.name, **measure(crt)})
    if CATALYST.exists():
        rows.append({"chain": "catalyst", **measure(CATALYST)})

    (HERE / "sizes.json").write_text(json.dumps(rows, indent=2) + "\n")

    by = {(r["chain"], Path(r["file"]).stem): r for r in rows}

    def cell(chain, part):
        r = by.get((chain, part))
        return f"{r['total']:,}" if r else ""

    md = ["# Corpus sizes (bytes, DER)", "",
          "Generated by `gen/sizes.py` from `gen/sizes.json`. Do not hand-edit.", "",
          "## Certificates (1 SAN)", "",
          "| Chain | Root | Intermediate | Leaf | Leaf SPKI | Leaf signature |",
          "|---|---|---|---|---|---|"]
    for chain in ["ecdsa", "mldsa44", "mldsa65", "mldsa87", "slhroot", "mixed"]:
        leaf = by.get((chain, "leaf"))
        md.append(
            f"| {chain} | {cell(chain,'root')} | {cell(chain,'int')} | {cell(chain,'leaf')} "
            f"| {leaf['spki']:,} | {leaf['signature']:,} |"
        )
    cat = by.get(("catalyst", "leaf"))
    if cat:
        md.append(f"| catalyst | (ECDSA CA) | | {cat['total']:,} | {cat['spki']:,} | {cat['signature']:,} |")

    md += ["", "## Wire cost (intermediate + leaf, what a TLS server sends)", "",
           "| Chain | Bytes | Delta vs control |", "|---|---|---|"]
    control = by[("ecdsa", "int")]["total"] + by[("ecdsa", "leaf")]["total"]
    for chain in ["ecdsa", "mldsa44", "mldsa65", "mldsa87", "slhroot", "mixed"]:
        wire = by[(chain, "int")]["total"] + by[(chain, "leaf")]["total"]
        md.append(f"| {chain} | {wire:,} | +{wire - control:,} |")

    md += ["", "## SAN ladder (leaf total bytes)", "",
           "| SANs | ecdsa | mldsa65 | delta |", "|---|---|---|---|"]
    for n, stem in [(1, "leaf"), (10, "leaf-san10"), (50, "leaf-san50"), (150, "leaf-san150")]:
        e = by[("ecdsa", stem)]["total"]
        m = by[("mldsa65", stem)]["total"]
        md.append(f"| {n} | {e:,} | {m:,} | +{m - e:,} |")

    (HERE.parent / "SIZES.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} certs measured; sizes.json and SIZES.md written")


if __name__ == "__main__":
    main()
